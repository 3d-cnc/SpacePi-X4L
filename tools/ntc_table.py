"""Generates firmware/src/ntc_table.h from the Steinhart-Hart equation.

The heater sensors of the X4L are 100 kOhm NTCs on a 4.7 kOhm voltage divider to 3.3 V
(R = 4700 * ADC / (4096 - ADC)). The three coefficients were fitted to measurements of the
installed sensor (0, 60, 130 °C); deviation over -15..150 °C below 0.2 K.

  python tools/ntc_table.py
"""
import math
import os

A, B, C = 7.010326e-04, 2.175973e-04, 9.620308e-08   # 1/T = A + B ln R + C (ln R)^3, T in K
T_MIN, POINTS = -15, 166                               # 1 °C steps from -15 to 150 °C


def resistance(t_c):
    """Solves the Steinhart-Hart equation for R."""
    y = 1.0 / (t_c + 273.15)
    x = (A - y) / C
    w = math.sqrt((B / (3 * C)) ** 3 + (x / 2) ** 2)
    return math.exp(math.copysign(abs(w - x / 2) ** (1 / 3), w - x / 2) - math.copysign(abs(w + x / 2) ** (1 / 3), w + x / 2))


def main():
    values = [round(resistance(T_MIN + i)) for i in range(POINTS)]
    assert all(values[i] > values[i + 1] for i in range(POINTS - 1)), "curve must be falling"
    target = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "firmware", "src", "ntc_table.h")
    lines = [
        "/* NTC curve of the heater sensors (100 kOhm, divider 4.7 kOhm to 3.3 V).",
        " * Generated by tools/ntc_table.py from the Steinhart-Hart equation",
        f" * (A={A:.6e}, B={B:.6e}, C={C:.6e}). Resistance in ohms per 1 degree C,",
        f" * index i belongs to {T_MIN} + i degrees C. Do not edit by hand. */",
        "#ifndef NTC_TABLE_H",
        "#define NTC_TABLE_H",
        "#include <stdint.h>",
        f"#define NTC_POINTS {POINTS}",
        "static const uint32_t NTC_OHM[NTC_POINTS] = {",
    ]
    for i in range(0, POINTS, 8):
        lines.append("    " + ", ".join(f"{v}u" for v in values[i:i + 8]) + ",")
    lines += ["};", "#endif", ""]
    with open(target, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"{target}: {POINTS} values, 25 °C = {values[25 - T_MIN]} ohms, 100 °C = {values[100 - T_MIN]} ohms")


if __name__ == "__main__":
    main()
